// 場面問題の自動生成：アウト数・ランナー・プレーの組み合わせから、毎回ちがう問題を作る。
// 答えは「ルールの判定」から計算する（決まった問題の答えを、手で書かない）。
// ルールの判定は、コーチ確認用の一覧（「自動生成の判定ルール」）に、そのまま書いてある。
const rnd=n=>Math.floor(Math.random()*n);
const pick=a=>a[rnd(a.length)];
const BN={1:'一塁',2:'二塁',3:'三塁'};
const rtext=r=>r.length===0?'ランナーなし':r.length===3?'満塁':'ランナー'+r.map(b=>BN[b]).join('と');
const nextName=b=>b===3?'ホームベース':BN[b+1]+'ベース';
const nextKey=b=>b===3?'H':String(b+1);
const dr=(runners,outs,arrows)=>{const o={runners:runners.map(String),outs};if(arrows)o.arrows=arrows;return o};
const mk=(diff,topic,q,choices,answer,explain,diagram,extra={})=>({gen:true,diff,topic,q,choices,answer,explain,basis:'自動生成：'+topic,diagram,...extra});

// ① フォース／タッチ
function force(lv){
  const sets=lv===1?[[1],[2],[1,2]]:lv===2?[[1],[2],[3],[1,2],[1,3],[2,3]]:[[1,2],[1,3],[2,3],[1,2,3]];
  const r=pick(sets),t=pick(r),outs=rnd(2);
  const forced=Array.from({length:t-1},(_,i)=>i+1).every(k=>r.includes(k));   // 後ろの塁が、すべてうまっている
  const arrows=[{from:String(t),to:nextKey(t)}];
  if(rnd(2)){
    return mk(lv,'フォース',`${rtext(r)}で、ゴロを打った。${BN[t]}にいたランナーをアウトにするとき、ランナーへのタッチは必要？`,['必要','必要ない','ランナーの足の速さ次第'],forced?1:0,
      forced?`${BN[t]}のランナーは、うしろの塁がうまっていて、進まないといけません（フォース）。ボールを持って、${nextName(t)}を踏めば、タッチなしでアウトです。`:`${BN[t]}のランナーは、うしろの塁が空いていて、押し出されません（フォースではない）。ボールで、ランナーにタッチしないと、アウトになりません。`,dr(r,outs,arrows));
  }
  return mk(lv,'フォース',`${rtext(r)}で、ゴロ。ボールを持った野手が、${nextName(t)}を踏んだ（ランナーにはタッチしていない）。${BN[t]}にいたランナーは？`,['アウト','セーフ','審判が決める'],forced?0:1,
    forced?`${BN[t]}のランナーは、フォースで、進まないといけません。${nextName(t)}を踏めば、タッチなしでアウトです。`:`${BN[t]}のランナーは、フォースではありません。${nextName(t)}を踏んでも、タッチしていないので、アウトになりません。`,dr(r,outs,arrows));
}

// ② インフィールドフライ
function iff(lv){
  const sets=lv===1?[[1,2],[1,2,3],[1],[]]:[[1,2],[1,2,3],[1],[2],[3],[2,3],[1,3],[]];
  const r=pick(sets),outs=lv===1?rnd(2):rnd(3);
  const balls=lv===1?['内野に高いフライ']:['内野に高いフライ','内野に高いフライ','外野の深いフライ','強いライナー','バントが小フライになったもの'];
  const ball=pick(balls),ok=ball==='内野に高いフライ';
  const ans=outs<2&&r.includes(1)&&r.includes(2)&&ok;
  let why;
  if(outs===2)why='アウトが2つのときは、宣告されません（アウトが0か1のときだけ）。';
  else if(!(r.includes(1)&&r.includes(2)))why='ランナーが「一・二塁」か「満塁」ではないので、宣告されません。';
  else if(!ok)why='「内野の、普通に捕れる高いフライ」ではない（外野の深いフライ、ライナー、バントは対象外）ので、宣告されません。';
  else why='アウトが0か1で、ランナーが一・二塁（または満塁）、内野の高いフライ。インフィールドフライが宣告されます。';
  return mk(lv,'インフィールドフライ',`${outs}アウト、${rtext(r)}。${ball}が上がった。インフィールドフライは宣告される？`,['宣告される','宣告されない','どちらとも言えない'],ans?0:1,why,dr(r,outs),
    ball==='バントが小フライになったもの'?{review:'バントのフライの扱い（要確認）'}:{});
}

// ③ 振り逃げ
function furi(lv){
  const sets=lv===1?[[],[1]]:lv===2?[[],[1],[2],[3]]:[[],[1],[2],[3],[1,2],[1,3],[2,3],[1,2,3]];
  const r=pick(sets),outs=rnd(3);
  if(lv===3&&rnd(4)===0){   // 第3ストライクではない投球（ワンバウンドしても、走れない）
    const b=rnd(3),s=rnd(2);
    return mk(4,'振り逃げ',`${outs}アウト、${rtext(r)}。カウントは${b}ボール${s}ストライク。バッターが空振り（${s+1}つ目のストライク）。投球はワンバウンドして、キャッチャーが、捕れなかった。バッターは？`,['走れない','一塁へ走れる','三振でアウト'],0,`走れるのは、「第3ストライク」の投球だけです。これは${s+1}つ目のストライクなので、ストライクが増えるだけで、バッターは走れません。${r.length?'（ランナーは、進塁できます）':''}`,dr(r,outs));
  }
  const catches=lv<3?['落とした','落とした','捕った']:['落とした','ワンバウンド','ワンバウンド','捕った'];
  const c=pick(catches),swing=pick(['空振り','見逃し']);
  const cText={'落とした':pick(['キャッチャーが、ボールを捕れなかった','キャッチャーが、ボールを落とした']),'ワンバウンド':'投球がワンバウンドして、キャッチャーが、ミットで捕った','捕った':'キャッチャーが、ノーバウンドで、しっかり捕った'}[c];
  const first=r.includes(1),caught=c==='捕った';
  const run=!caught&&(!first||outs===2);
  let why;
  if(caught)why='キャッチャーが、ワンバウンドせずに、しっかり捕ったので、ふつうの三振でアウトです。';
  else if(!first)why=`一塁が空いているので、バッターは、一塁へ走れます（振り逃げ）。${c==='ワンバウンド'?'ワンバウンドで捕っても、「正規の捕球」ではありません。':''}`;
  else if(outs===2)why=`2アウトなので、一塁にランナーがいても、振り逃げできます。${c==='ワンバウンド'?'（ワンバウンドで捕っても、「正規の捕球」ではありません）':''}`;
  else why=`一塁にランナーがいて、アウトが${outs}つ（2アウトではない）なので、振り逃げはできません。三振でアウトです。${c==='ワンバウンド'?'（ワンバウンドで捕っても、「正規の捕球」ではない点は、同じ）':''}`;
  const sw=swing==='空振り'?'空振り三振':'バットを振らずに三振（見逃し）';
  return mk(lv+(lv===3?1:0),'振り逃げ',`${outs}アウト、${rtext(r)}。${sw}。${cText}。バッターは？`,['一塁へ走れる','三振でアウト','走れるかは、審判が決める'],run?0:1,why,dr(r,outs));
}

// ④ ボーク
function balk(lv){
  const A=[ // [動作, ボークか, 必要なランナー]
    ['セットポジションで、止まらずに（途中で止めずに）投げた',true,[]],
    ['投球の途中で、ボールを落とした',true,[]],
    ['足を投手板に置いたまま、一塁へけん制するふりだけして、投げなかった',true,[1]],
    ['足を投手板に置いたまま、三塁へけん制するふりだけして、投げなかった',true,[3]],
    ['セットポジションで、いったん完全に止まってから、投げた',false,[]],
    ['軸足を投手板から外してから、一塁へけん制した',false,[1]],
    ['軸足を投手板から外してから、けん制するふりだけして、投げなかった',false,[]],
    ['足を投手板に置いたまま、二塁へけん制するふりだけして、投げなかった',false,[2]],
  ];
  const [text,bad,need]=pick(lv===1?A.slice(0,6):A);
  let r=[...new Set([...need,...(rnd(2)?[pick([1,2,3])]:[])])];if(r.length===0)r=[pick([1,2,3])];
  const outs=rnd(2);
  const exp=bad?'この動きは、ランナーがいるときは、ボークです。ボールデッドになり、ランナー全員が、1つずつ進みます。':'この動きは、反則ではありません。ボークにはなりません。';
  return mk(lv,'ボーク',`${outs}アウト、${rtext(r)}。ピッチャーが、${text}。審判の判断は？`,['ボーク','ボークではない','ストライク'],bad?0:1,exp,dr(r,outs),{review:(text.includes('二塁へ')?'二塁へのふりの扱い（要確認）':'ボークの細かい条件（要確認）')});
}

// ⑤ 3アウト目と得点
function tori(){
  const type=pick(['A','B','C']);
  const before=rnd(2)===0;   // 三塁ランナーが、3つ目のアウトより先にホームを踏んだか
  let r,desc;
  if(type==='A'){r=pick([[3],[1,3],[2,3],[1,2,3]]);desc='内野ゴロ。バッターが、一塁に着く前に、アウトになった（3アウト目）';}
  else if(type==='B'){r=pick([[1,3],[1,2,3]]);desc='バッターがヒットを打って、一塁にセーフ。そのあと、一塁にいたランナーが、二塁でフォースアウト（3アウト目）';}
  else{r=pick([[3],[1,3],[2,3],[1,2,3]]);desc='バッターがヒットを打って、一塁にセーフ。そのあと、二塁をねらって、タッチアウト（3アウト目）';}
  const when=before?'そのアウトより先に、ホームを踏んでいた':'そのアウトのあとで、ホームに入ろうとしていた（まだ踏んでいない）';
  const ans=before&&type==='C';
  let why;
  if(!before)why='3つ目のアウトで、攻撃が終わります。そのあとにホームを踏んでも、得点にはなりません。';
  else if(type==='A')why='3つ目のアウトが、バッターが一塁に着く前のアウトなので、先にホームを踏んでいても、得点は入りません。';
  else if(type==='B')why='3つ目のアウトが、フォースアウトなので、先にホームを踏んでいても、得点は入りません。';
  else why='3つ目のアウトが、フォースアウトでも、バッターが一塁に着く前のアウトでもない（タッチアウト）ので、先にホームを踏んでいれば、得点は入ります。';
  return mk(4,'3アウト目と得点',`2アウト、${rtext(r)}。${desc}。三塁ランナーは、${when}。三塁ランナーの得点は？`,['1点入る','入らない','審判が決める'],ans?0:1,why,dr(r,2),{review:'3アウト目と得点の条件（要確認）'});
}

// ⑥ タッチアップ（フライと、ゴロ・落ちた場合の区別）
function tag(lv){
  const r=pick(lv===2?[[1],[2],[3],[1,2],[2,3]]:[[1],[2],[3],[1,2],[1,3],[2,3],[1,2,3]]),t=pick(r),outs=rnd(2);
  const caught=['外野フライが、捕られた','外野フライを、外野手が、ジャンプして捕った','ファウルのフライが、捕られた'];
  const notCaught=['外野フライが、野手の間に落ちた（捕られていない）','ゴロを打って、野手が、はじいた（まだアウトになっていない）'];
  const useCaught=lv===2?rnd(4)>0:rnd(2)===0;
  const arrows=[{from:String(t),to:nextKey(t)}];
  if(useCaught)return mk(lv,'タッチアップ',`${outs}アウト、${rtext(r)}。${pick(caught)}。${BN[t]}のランナーが、${nextName(t)==='ホームベース'?'ホームへ':BN[t+1]+'へ'}進むには？`,['ボールが捕られたあとに、元の塁に触れてから進む','ボールが捕られる前に、走り出してよい','捕られたら、進んではいけない'],0,'フライが捕られたあとは、元の塁に触れて（タッチアップ）から、進みます。捕られる前に走り出すと、元の塁に戻って、ボールで塁を踏まれたら、アウトになります。',dr(r,outs,arrows));
  return mk(lv,'タッチアップ',`${outs}アウト、${rtext(r)}。${pick(notCaught)}。${BN[t]}のランナーは、タッチアップが必要？`,['必要ない','必要','必ず、元の塁に戻る'],0,'タッチアップが必要なのは、フライが「捕られたとき」です。捕られていないボールなら、ランナーは、タッチアップなしで、走ってよいです（アウトにならないよう、気をつけて）。',dr(r,outs,arrows),{review:'ゴロをはじいた場合などの細かい扱い（要確認）'});
}

