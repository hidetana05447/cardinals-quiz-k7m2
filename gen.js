  return mk(lv,'妨害',q+'。これは、何の反則？',['打撃妨害','走塁妨害','守備妨害'],['打撃妨害','走塁妨害','守備妨害'].indexOf(a),ex,undefined,lv===3?{review:'故意かどうかなどの細かい扱い（要確認）'}:{});
